// Helper functions
export function getCountyBySlug(slug: string): County | undefined {
  return COUNTIES_DATA.find(c => c.slug === slug);
}

export function getLocationBySlug(countySlug: string, locationSlug: string): Location | undefined {
  const county = getCountyBySlug(countySlug);
  return county?.locations.find(l => l.slug === locationSlug);
}

export function getAllLocations(): (Location & { countySlug: string; countyName: string })[] {
  return COUNTIES_DATA.flatMap(c =>
    c.locations.map(l => ({ ...l, countySlug: c.slug, countyName: c.name }))
  );
}

export function getLocationCount(): number {
  return COUNTIES_DATA.reduce((sum, c) => sum + c.locations.length, 0);
}
